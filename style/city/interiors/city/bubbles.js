// ── the bubble's body: a white box with chunky corners (r cells), the ink drop one cell down-right; say: a stepped tail under its
// left end; think: two trailing dots. mirrored for side 'R' (the box to the left of the head). → { w, h, ax, ay } (cells; anchor)
const CUT = { say: [2, 1], think: [4, 2, 1, 1] };
function body(ctx, W, H, kind, side, ink) {
  const cut = CUT[kind], fx = side === 'R' ? (x, w) => W - x - w : x => x;
  const shape = (dx, dy, c) => { ctx.fillStyle = c; const rect = (x, y, w, h) => ctx.fillRect(fx(x, w) + dx, y + dy, w, h);
    for (let y = 0; y < H; y++) { const k = cut[y] ?? cut[H - 1 - y] ?? 0; rect(k, y, W - 2 * k, 1); }
    if (kind === 'say') { rect(3, H, 4, 1); rect(2, H + 1, 3, 1); rect(1, H + 2, 2, 1); }
    else { rect(3, H + 1, 2, 2); rect(1, H + 4, 1, 1); } };
  shape(1, 1, ink); shape(0, 0, PAL.w);
  return { ax: side === 'R' ? W - 2 : 1, ay: kind === 'say' ? H + 3 : H + 5 };
}

