export function createBubbles(dom) {
  css(); const el = document.createElement('div'), inner = document.createElement('div'), cv = document.createElement('canvas'), ctx = cv.getContext('2d');
  el.className = 'hlb'; el.hidden = true; inner.appendChild(cv); el.appendChild(inner); dom.appendChild(el);
  const zz = document.createElement('div'); zz.className = 'hlb zz'; zz.hidden = true; dom.appendChild(zz);
  let S = 0, cur = null, t = 0, life = 0, drawn = '', anchor = [0, 0];
  const scaleNow = () => { const h = Math.min((dom.clientWidth || innerWidth) * .75, dom.clientHeight || innerHeight); return Math.max(2, Math.min(4, Math.round(h / 300))); };   // (3 at 1280 × 800, 2 on a phone)
  function zzBuild() { zz.textContent = ''; zz.style.setProperty('--s', S);
    for (const [g, k] of [[Z4, S], [Z5, S], [Z5, S + 1]]) { const c = document.createElement('canvas'), n = g.length; c.width = c.height = n + 1; const x = c.getContext('2d');
      for (let y = 0; y < n; y++) for (let i = 0; i < n; i++) if (g[y][i] !== '.') { x.fillStyle = PAL.b; x.fillRect(i + 1, y + 1, 1, 1); }
      grid(x, g, 0, 0); c.style.width = c.style.height = (n + 1) * k + 'px'; zz.appendChild(c); } }
  // draw the current bubble at its time (only when something on it changed: the icons' frames, the second icon arriving)
  function draw() {
    const ids = cur.ids, two = ids.length > 1, reveal = two ? (t > .62 ? 2 : t > .42 ? 1 : 0) : 0;
    const key = ids.map(id => Math.floor(t / .3) % (I[id]?.f.length || 1)).join() + '|' + reveal + '|' + S + cur.side;
    if (key === drawn) return; drawn = key;
    const W = two ? 2 + N + 1 + 4 + 1 + N + 2 : N + 4, H = N + 4, kind = cur.kind;
    const cw = W + 1, ch = H + (kind === 'say' ? 3 : 5) + 1;
    if (cv.width !== cw || cv.height !== ch) { cv.width = cw; cv.height = ch; } else ctx.clearRect(0, 0, cw, ch);
    cv.style.width = cw * S + 'px'; cv.style.height = ch * S + 'px';
    const a = body(ctx, W, H, kind, cur.side, PAL.k);
    grid(ctx, frameOf(ids[0], t), 2, 2);
    if (two && reveal >= 1) grid(ctx, ARROW, 2 + N + 1, 2 + 4);
    if (two && reveal >= 2) grid(ctx, frameOf(ids[1], t - .62), 2 + N + 1 + 4 + 1, 2);
    anchor = [(a.ax + .5) * S, a.ay * S]; inner.style.setProperty('--ox', anchor[0] + 'px'); inner.style.setProperty('--oy', anchor[1] + 'px');
  }
  function show(ids, dur, kind, side) { S = scaleNow(); if (zz.dataset.s !== String(S)) { zz.dataset.s = S; zzBuild(); }
    cur = { ids: ids.filter(id => I[id]), kind, side: side === 'R' ? 'R' : 'L' }; if (!cur.ids.length) { cur = null; return; }
    t = 0; life = dur; drawn = ''; draw(); el.hidden = false; inner.classList.remove('out'); void inner.offsetWidth; inner.style.animation = 'none'; void inner.offsetWidth; inner.style.animation = ''; }
  return {
    say(id, dur = 1.8, side) { show([id], dur, 'say', side); },
    think(ids, dur = 2.8, side) { show([].concat(ids), dur, 'think', side); },
    sleep(on) { if (on && !S) { S = scaleNow(); zz.dataset.s = S; zzBuild(); } zz.hidden = !on; },
    // per frame: dt, and where the head's top is (css px in dom); the bubble's anchor goes there, the z's a little to the side
    update(dt, x, y, on = true) {
      if (cur) { t += dt; life -= dt; if (life <= .24 && life + dt > .24) inner.classList.add('out'); if (life <= 0) { cur = null; el.hidden = true; } else draw(); }
      const vis = on ? '' : 'hidden', DW = dom.clientWidth || innerWidth, w = cv.width * S;
      if (cur && cur.side === 'L' && x - anchor[0] + w > DW - 4 && x - w > 4) { cur.side = 'R'; draw(); }   // (at the view's edge: to the head's other side)
      else if (cur && cur.side === 'R' && x - anchor[0] < 4 && x + w < DW - 4) { cur.side = 'L'; draw(); }
      if (!el.hidden) { el.style.visibility = vis; el.style.transform = `translate3d(${Math.round(x - anchor[0])}px, ${Math.round(y - anchor[1])}px, 0)`; }
      if (!zz.hidden) { zz.style.visibility = vis; zz.style.transform = `translate3d(${Math.round(x + 2 * S)}px, ${Math.round(y)}px, 0)`; } },
    shown: () => cur && { ids: cur.ids, kind: cur.kind, t },
    get busy() { return !!cur; },
    dispose() { el.remove(); zz.remove(); },
  };
}
